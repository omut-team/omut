namespace Omut.Core
{
    // Все состояния (фазы) игры. В каждый момент игра находится ровно в одном из них.
    public enum GameState
    {
        Menu,     // главное меню
        Sailing,  // плаваем на лодке или ходим по причалу
        Fishing,  // рыбачим: заброс, поклёвка, вываживание
        Shop,     // открыт магазин или разговор с торговцем
        Paused    // пауза (Esc), время остановлено
    }
}
